    /**
     * @return list<Grape>
     */
    public static function all(): array
    {
        $grapes = array_map(fn (array $row) => [
            'name' => $row[0],
            'color' => $row[1],
            'origin' => $row[2],
            'aliases' => $row[3] ?? [],
            'popular' => $row[4] ?? false,
        ], self::LIST);

        usort($grapes, fn (array $a, array $b) => strcmp(self::sortKey($a['name']), self::sortKey($b['name'])));

        return $grapes;
    }

    /**
     * The name of each grape, for validation or suggestions.
     *
     * @return list<string>
     */
    public static function names(): array
    {
        return array_column(self::all(), 'name');
    }

    private static function sortKey(string $name): string
    {
        return mb_strtolower(Str::ascii($name));
    }
